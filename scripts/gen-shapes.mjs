// Writes the Material shapes the app draws (src/components/common/Shape.jsx) as SVG path data, so
// the shape geometry is computed here at build time and @kyralabs/m3e-shapes never ships to the
// browser. Paths are in a 0–1 box, rounded to three decimals.
import { mkdirSync, writeFileSync } from 'node:fs';
import { materialShape, polygonToPath, toSvgPathData } from '@kyralabs/m3e-shapes';

const names = ['Cookie4Sided', 'Cookie9Sided', 'Clover4Leaf', 'Flower', 'Pill', 'Sunny'];

const out = new URL('../src/styles/generated/shapes.js', import.meta.url);
mkdirSync(new URL('.', out), { recursive: true });
const paths = Object.fromEntries(
  names.map((name) => [
    name,
    toSvgPathData(polygonToPath(materialShape(name))).replace(/\d*\.\d+/g, (n) =>
      String(Math.round(Number(n) * 1000) / 1000),
    ),
  ]),
);
writeFileSync(
  out,
  `// Generated by scripts/gen-shapes.mjs. Do not edit.\nexport const shapePaths = ${JSON.stringify(paths, null, 2)};\n`,
);
console.log(`shapes: ${names.join(', ')} -> src/styles/generated/shapes.js`);
