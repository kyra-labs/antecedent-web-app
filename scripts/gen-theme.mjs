// Writes the brand colour scheme for the app's theme toggle (src/components/common/ThemeProvider):
// light on :root (also covers [data-theme='light']), dark on [data-theme='dark'], which wins on
// specificity.
import { mkdirSync, writeFileSync } from 'node:fs';
import { createTheme } from '@kyralabs/m3e-tokens/theme';
import { brand } from '../src/brand.mjs';

const out = new URL('../src/styles/generated/theme.css', import.meta.url);
mkdirSync(new URL('.', out), { recursive: true });
const light = createTheme({ ...brand, mode: 'light', selector: ':root' }).cssText;
const dark = createTheme({ ...brand, mode: 'dark', selector: ":root[data-theme='dark']" }).cssText;
writeFileSync(
  out,
  `/* Generated by scripts/gen-theme.mjs from src/brand.mjs. Do not edit. */\n${light}\n${dark}`,
);
console.log(`theme: ${brand.seed} (${brand.variant}) -> src/styles/generated/theme.css`);
